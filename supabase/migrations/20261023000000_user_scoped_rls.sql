/*
# Scope all data to the signed-in user

The original migration created `transactions` as a single-tenant table with
anon CRUD policies. The app now uses Supabase Auth and filters by `user_id`,
and the live database already has `user_id`, `push_subscriptions` and
`ai_usage`, but none of that was captured in migrations. This brings the repo
in line and makes the database (not the client) enforce ownership.

`user_id` is `text` on the live tables, so it is kept as text here and
compared against `auth.uid()::text`. Every statement is idempotent so this is
safe to run against the existing project.

1. Schema
- `transactions.user_id` (text)
- `push_subscriptions` (endpoint-unique web push subscriptions per user)
- `ai_usage` (one row per ai-proxy call, used for per-user rate limiting)
2. Security
- Drop the anon `USING (true)` policies on `transactions`.
- Authenticated users can only read and write their own rows.
- `ai_usage` has RLS enabled with no policies: only the service role
  (used by the ai-proxy edge function) can touch it.
*/

ALTER TABLE transactions ADD COLUMN IF NOT EXISTS user_id text;
CREATE INDEX IF NOT EXISTS idx_transactions_user_date
  ON transactions (user_id, transaction_date DESC);

DROP POLICY IF EXISTS "anon_select_transactions" ON transactions;
DROP POLICY IF EXISTS "anon_insert_transactions" ON transactions;
DROP POLICY IF EXISTS "anon_update_transactions" ON transactions;
DROP POLICY IF EXISTS "anon_delete_transactions" ON transactions;

-- Policy names and expressions match the live project. `(select auth.uid())`
-- lets Postgres evaluate the uid once per query instead of once per row.
DROP POLICY IF EXISTS "Users can view their own transactions" ON transactions;
CREATE POLICY "Users can view their own transactions" ON transactions FOR SELECT
TO authenticated USING ((select auth.uid())::text = user_id);

DROP POLICY IF EXISTS "Users can insert their own transactions" ON transactions;
CREATE POLICY "Users can insert their own transactions" ON transactions FOR INSERT
TO authenticated WITH CHECK ((select auth.uid())::text = user_id);

DROP POLICY IF EXISTS "Users can update their own transactions" ON transactions;
CREATE POLICY "Users can update their own transactions" ON transactions FOR UPDATE
TO authenticated USING ((select auth.uid())::text = user_id);

DROP POLICY IF EXISTS "Users can delete their own transactions" ON transactions;
CREATE POLICY "Users can delete their own transactions" ON transactions FOR DELETE
TO authenticated USING ((select auth.uid())::text = user_id);

CREATE TABLE IF NOT EXISTS push_subscriptions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id text NOT NULL,
  endpoint text NOT NULL,
  p256dh text NOT NULL,
  auth text NOT NULL,
  created_at timestamptz DEFAULT now()
);

-- The client upserts with onConflict: 'endpoint'.
CREATE UNIQUE INDEX IF NOT EXISTS push_subscriptions_endpoint_key
  ON push_subscriptions (endpoint);
CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user
  ON push_subscriptions (user_id);

ALTER TABLE push_subscriptions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can manage own subscriptions" ON push_subscriptions;
CREATE POLICY "Users can manage own subscriptions" ON push_subscriptions FOR ALL
TO authenticated USING (auth.uid()::text = user_id) WITH CHECK (auth.uid()::text = user_id);

CREATE TABLE IF NOT EXISTS ai_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL,
  action text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ai_usage_user_created
  ON ai_usage (user_id, created_at DESC);

ALTER TABLE ai_usage ENABLE ROW LEVEL SECURITY;
